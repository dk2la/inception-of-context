"""Optional auto-commit of validated patches, with a commit message written by the local model."""
from __future__ import annotations

import subprocess
from pathlib import Path

GIT = ["git", "-c", "user.name=Inception-of-Context", "-c", "user.email=ioc@localhost", "-c", "safe.directory=*"]


def _git(target: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run([*GIT, *args], cwd=target, capture_output=True, text=True, timeout=30)


def is_repo(target: Path) -> bool:
    try:
        r = _git(target, "rev-parse", "--show-toplevel")
    except (OSError, subprocess.TimeoutExpired):
        return False
    return r.returncode == 0 and Path(r.stdout.strip()).resolve() == target.resolve()


def commit_message(llm, model: str, summary: str, files: list[str]) -> str:
    prompt = ("Write ONE git commit subject line (imperative mood, at most 72 characters, no quotes, no period) "
              f"for this change.\nSummary: {summary}\nFiles: {', '.join(files)}")
    try:
        msg = llm.chat(model, [{"role": "user", "content": prompt}], temperature=0.2, num_predict=40).strip()
    except Exception:
        msg = ""
    msg = msg.splitlines()[0].strip().strip("\"'`").rstrip(".") if msg else ""
    return (msg or summary or "Apply IoC patch")[:72]


def commit(target: Path, files: list[str], message: str) -> dict:
    if not is_repo(target):
        return {"ok": False, "skipped": True, "reason": "target is not the root of a git repository"}
    _git(target, "add", "-A", "--", *files)
    r = _git(target, "commit", "-m", message, "-m", "Generated by Inception-of-Context patch loop", "--", *files)
    if r.returncode != 0:
        return {"ok": False, "reason": (r.stdout + r.stderr).strip()[:500]}
    sha = _git(target, "rev-parse", "--short", "HEAD").stdout.strip()
    return {"ok": True, "sha": sha, "message": message}


def log(target: Path, n: int = 10) -> list[dict]:
    if not is_repo(target):
        return []
    r = _git(target, "log", f"-{n}", "--pretty=format:%h%x09%ad%x09%s", "--date=format:%Y-%m-%d %H:%M")
    return [dict(zip(("sha", "date", "subject"), line.split("\t", 2))) for line in r.stdout.splitlines() if line]
